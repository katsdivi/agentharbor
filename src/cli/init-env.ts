#!/usr/bin/env node
/**
 * Creates a .env from .env.example with freshly generated local secrets. Never
 * overwrites an existing .env and never prints secret values.
 *
 * Where it is written (first that applies):
 *   RBA_ENV_FILE                 explicit file
 *   --target <dir>               <dir>/.env
 *   --plugin-data <marketplace>  ~/.claude/plugins/data/remote-browser-accounts-<marketplace>/.env,
 *                                the folder Claude Code keeps across plugin updates
 *   $CLAUDE_PLUGIN_DATA/.env     when run by Claude Code
 *   <plugin root>/.env           source checkout (the legacy location)
 * With --add-missing-generated, appends only generated keys that are absent.
 */
import { randomBytes } from 'node:crypto';
import { appendFileSync, chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { parseEnv } from 'node:util';
import { PROJECT_ROOT, envFileCandidates, hasRegistry, isPlaceholder } from '../core/config.js';
import { pluginDataDir } from './install-checks.js';

const argv = process.argv.slice(2);
const opt = (name: string): string | undefined => {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : undefined;
};

function targetEnvFile(): string {
  if (process.env.RBA_ENV_FILE) return resolve(process.env.RBA_ENV_FILE);
  const t = opt('--target');
  if (t) return join(resolve(t), '.env');
  const m = opt('--plugin-data');
  if (m) return join(pluginDataDir(m), '.env');
  if (process.env.CLAUDE_PLUGIN_DATA) return join(process.env.CLAUDE_PLUGIN_DATA, '.env');
  return join(PROJECT_ROOT, '.env');
}

const envPath = targetEnvFile();
const examplePath = join(PROJECT_ROOT, '.env.example');
const generated: Record<string, () => string> = {
  RBA_ENCRYPTION_KEY: () => randomBytes(32).toString('base64'),
  RBA_DASHBOARD_TOKEN: () => randomBytes(32).toString('base64url'),
};

if (existsSync(envPath)) {
  const cur = parseEnv(readFileSync(envPath, 'utf8')) as Record<string, string>;
  const missing = Object.keys(generated).filter((k) => isPlaceholder(cur[k]));
  if (missing.length && argv.includes('--add-missing-generated')) {
    const present = Object.keys(cur);
    const toAppend = missing.filter((k) => !present.includes(k));
    if (toAppend.length < missing.length) {
      console.log(`Not modified: ${missing.filter((k) => present.includes(k)).join(', ')} exist with placeholder values; edit them by hand.`);
    }
    if (toAppend.length) appendFileSync(envPath, `\n# generated by init-env\n${toAppend.map((k) => `${k}=${generated[k]!()}`).join('\n')}\n`);
    console.log(toAppend.length ? `Appended generated values for: ${toAppend.join(', ')}` : 'Nothing appended.');
  } else {
    console.log(`.env already exists at ${envPath}; left untouched.${missing.length ? ` Missing generated values: ${missing.join(', ')} (run with --add-missing-generated to append them).` : ''}`);
  }
  chmodSync(envPath, 0o600);
} else {
  // A new .env in the plugin data folder takes priority over a legacy one. If the
  // legacy one already has accounts next to it, refuse: the server would refuse to
  // start rather than silently switch to empty data and a different key.
  const legacy = envFileCandidates({ ...process.env, CLAUDE_PLUGIN_DATA: undefined, RBA_ENV_FILE: undefined })
    .filter((c) => resolve(c) !== envPath && existsSync(c) && hasRegistry(join(dirname(c), 'data')));
  if (legacy.length) {
    console.error(`Refusing to create ${envPath}: existing data is next to ${legacy.join(', ')}.`);
    console.error('Keep using that install, or copy it with: npm run migrate-data -- --target <dir>. Nothing was written.');
    process.exit(2);
  }
  let text = readFileSync(examplePath, 'utf8');
  for (const [k, gen] of Object.entries(generated)) {
    text = text.replace(new RegExp(`^${k}=.*$`, 'm'), `${k}=${gen()}`);
  }
  mkdirSync(dirname(envPath), { recursive: true, mode: 0o700 });
  writeFileSync(envPath, text, { mode: 0o600, flag: 'wx' });
  console.log(`Created ${envPath} (mode 600) with generated RBA_ENCRYPTION_KEY and RBA_DASHBOARD_TOKEN.`);
  console.log('Fill in provider credentials yourself in that file (never in chat); run check-config to see what is missing.');
  console.log('Back up this file: the encryption key in it is the only way to read the stored accounts.');
}
